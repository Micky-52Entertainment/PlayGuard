const DICT: Record<Lang, Record<string, string>> = { en, ru, fr };

/** Every interface language, in the order the switches show them. */
export const LANGS: Array<{ id: Lang; code: string; label: string }> = [
  { id: "ru", code: "RU", label: "Русский" },
  { id: "en", code: "EN", label: "English" },
  { id: "fr", code: "FR", label: "Français" },
];

const isLang = (value: unknown): value is Lang => LANGS.some((item) => item.id === value);

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

const initialLang = (): Lang => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isLang(saved)) {
      return saved;
    }
  } catch {
    // Storage is blocked; fall back to the browser's language.
  }
  const browser = typeof navigator !== "undefined" ? (navigator.language || "").slice(0, 2).toLowerCase() : "";
  return isLang(browser) ? browser : "en";
};

let currentLang: Lang = initialLang();

/** The interface language, for code outside React (requests that ask for a report language). */
export const getLang = (): Lang => currentLang;

const plural = (lang: Lang, forms: string[], n: number): string => {
  if (lang === "ru") {
    const mod10 = n % 10;
    const mod100 = n % 100;
    const index = mod10 === 1 && mod100 !== 11 ? 0 : mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20) ? 1 : 2;
    return forms[Math.min(index, forms.length - 1)];
  }
  // French counts 0 and 1 as singular.
  return forms[(lang === "fr" ? n < 2 : n === 1) ? 0 : Math.min(1, forms.length - 1)];
};

export const translate = (lang: Lang, key: string, vars?: Record<string, string | number>): string => {
  let text = DICT[lang][key] ?? DICT.en[key] ?? "";
  if (vars && typeof vars.n === "number" && text.includes("|")) {
    text = plural(lang, text.split("|"), vars.n);
  }
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
  }
  return text;
};

/** A check's title in the interface language; the hub writes them in English. */
export const checkTitle = (t: Translate, lang: Lang, check: { id: string; title: string }): string => {
  if (lang === "en") {
    return check.title;
  }
  const own = t(`check.${check.id}` as Key);
  if (!own) {
    return check.title;
  }
  // "AppLovin integration": keep the network's name, translate the rest.
  const named = /^(.+) (integration|restrictions|lifecycle calls)$/.exec(check.title);
  return own.replace("{name}", named ? named[1] : "");
};

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

const Context = createContext<I18n>({
  lang: currentLang,
  setLang: () => undefined,
  t: (key, vars) => translate(currentLang, key, vars),
});

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(currentLang);
  const setLang = useCallback((next: Lang): void => {
    currentLang = next;
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      // The choice lasts until the page is closed.
    }
    setLangState(next);
  }, []);
  const value = useMemo<I18n>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    [lang, setLang]
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
};

export const useI18n = (): I18n => useContext(Context);
